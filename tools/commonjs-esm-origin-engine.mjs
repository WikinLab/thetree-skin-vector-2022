import fs from 'node:fs';
import path from 'node:path';
import { build } from 'esbuild';

function normalize(value) {
  return String(value).replace(/\r\n?/g, '\n').replace(/\s*$/, '');
}

function normalizePath(value) {
  return String(value || '').replaceAll('\\', '/').replace(/^\.\//, '');
}

function assertRelativePath(value, owner) {
  const pathname = normalizePath(value);
  if (!pathname || path.isAbsolute(pathname) || pathname.split('/').includes('..')) {
    throw new Error(`${owner} must use a project-relative path: ${value}`);
  }
  return pathname;
}

function assertIdentifier(value, owner) {
  if (!/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(value)) {
    throw new Error(`${owner} declares an invalid ESM export name: ${value}`);
  }
  return value;
}

async function renderBundle(root, definition) {
  const owner = `CommonJS ESM bundle ${definition?.id || '<unknown>'}`;
  const output = assertRelativePath(definition?.output, owner);
  const entries = Object.entries(definition?.exports || {});
  if (entries.length === 0) throw new Error(`${owner} has no declared exports.`);

  const sources = entries.map(([exportName, source], index) => {
    const identifier = assertIdentifier(exportName, owner);
    const input = assertRelativePath(source, owner);
    const absolute = path.join(root, input);
    if (!fs.existsSync(absolute) || !fs.statSync(absolute).isFile()) {
      throw new Error(`${owner} input is missing: ${input}`);
    }
    return { exportName: identifier, local: `__originExport${index}`, input };
  });
  const source = [
    ...sources.map(({ local, input }) => `import ${local} from './${input}';`),
    `export { ${sources.map(({ exportName, local }) => `${local} as ${exportName}`).join(', ')} };`
  ].join('\n');
  const externalModules = new Set(definition.external || []);
  const externalNamespace = 'commonjs-esm-external';
  const commonJsNamespace = 'commonjs-esm-js-input';
  const commonJsSuffix = '.origin.cjs';
  const commonJsRoots = (definition.commonJsRoots || []).map((value) => {
    const pathname = assertRelativePath(value, owner).replace(/\/$/, '');
    return { pathname, absolute: path.resolve(root, pathname) };
  });
  const isWithin = (candidate, directory) => {
    const relative = path.relative(directory, candidate);
    return relative === '' || (!relative.startsWith('..') && !path.isAbsolute(relative));
  };
  const commonJsInputPlugin = commonJsRoots.length ? {
    name: 'commonjs-esm-js-input',
    setup(context) {
      context.onResolve({ filter: /\.(?:c?js)$/ }, (args) => {
        if (!args.path.startsWith('.') && !path.isAbsolute(args.path)) return null;
        const candidate = path.resolve(args.resolveDir || path.dirname(args.importer), args.path);
        if (!commonJsRoots.some(({ absolute }) => isWithin(candidate, absolute))) return null;
        if (!fs.existsSync(candidate) || !fs.statSync(candidate).isFile()) return null;
        const input = assertRelativePath(path.relative(root, candidate), owner);
        return { path: `${input}${commonJsSuffix}`, namespace: commonJsNamespace };
      });
      context.onLoad({ filter: /.*/, namespace: commonJsNamespace }, (args) => {
        if (!args.path.endsWith(commonJsSuffix)) throw new Error(`${owner} received an invalid virtual CommonJS path.`);
        const input = args.path.slice(0, -commonJsSuffix.length);
        return {
          contents: fs.readFileSync(path.join(root, input), 'utf8'),
          loader: 'js',
          resolveDir: path.dirname(path.join(root, input))
        };
      });
    }
  } : null;
  const externalPlugin = externalModules.size ? {
    name: 'commonjs-esm-external',
    setup(context) {
      context.onResolve({ filter: /.*/ }, (args) => {
        if (!externalModules.has(args.path)) return null;
        if (args.namespace === externalNamespace) return { path: args.path, external: true };
        return { path: args.path, namespace: externalNamespace };
      });
      context.onLoad({ filter: /.*/, namespace: externalNamespace }, (args) => ({
        contents: `import * as value from ${JSON.stringify(args.path)}; module.exports = value;`,
        loader: 'js'
      }));
    }
  } : null;
  const result = await build({
    absWorkingDir: root,
    banner: {
      js: `// @generated by commonjs-esm-origin from the exact locked ${definition.id} CommonJS graph.`
    },
    bundle: true,
    charset: 'utf8',
    format: 'esm',
    legalComments: 'none',
    logLevel: 'silent',
    metafile: true,
    minify: false,
    platform: 'browser',
    plugins: [commonJsInputPlugin, externalPlugin].filter(Boolean),
    preserveSymlinks: true,
    sourcemap: false,
    stdin: {
      contents: source,
      loader: 'js',
      resolveDir: root,
      sourcefile: `${definition.id}.origin-entry.js`
    },
    target: definition.target || 'es2020',
    treeShaking: true,
    write: false
  });
  if (result.outputFiles?.length !== 1) {
    throw new Error(`${owner} must produce exactly one ESM JavaScript output; found ${result.outputFiles?.length || 0}.`);
  }
  const [outputFile] = result.outputFiles;
  const inputs = Object.keys(result.metafile?.inputs || {})
    .map((value) => {
      const normalized = normalizePath(value);
      const prefix = `${commonJsNamespace}:`;
      if (!normalized.startsWith(prefix) || !normalized.endsWith(commonJsSuffix)) return normalized;
      return normalized.slice(prefix.length, -commonJsSuffix.length);
    })
    .filter((input) => (
      input &&
      !input.includes(`${externalNamespace}:`) &&
      !input.endsWith('.origin-entry.js') &&
      input !== '<stdin>'
    ))
    .sort();
  for (const { input } of sources) {
    if (!inputs.includes(input)) throw new Error(`${owner} did not consume declared entry ${input}.`);
  }
  return {
    content: `${normalize(outputFile.text)}\n`,
    inputs,
    output,
    primaryInput: sources[0].input
  };
}

function writeOutput(root, result, check) {
  const target = path.join(root, result.output);
  if (check) {
    if (!fs.existsSync(target) || normalize(fs.readFileSync(target, 'utf8')) !== normalize(result.content)) {
      throw new Error(`Generated CommonJS ESM bundle is stale: ${result.output}`);
    }
    return;
  }
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, result.content);
}

export async function generateCommonJsEsmOrigins({ root, contractPath, check = false }) {
  const contract = JSON.parse(fs.readFileSync(path.join(root, contractPath), 'utf8'));
  if (contract.schema !== 1 || !Array.isArray(contract.bundles) || contract.bundles.length === 0) {
    throw new Error(`Unsupported or empty CommonJS ESM origin contract: ${contractPath}`);
  }
  const results = [];
  for (const definition of contract.bundles) results.push(await renderBundle(root, definition));
  for (const result of results) writeOutput(root, result, check);
  return {
    inputs: [...new Set(results.flatMap((result) => result.inputs))].sort(),
    outputs: results.map((result) => result.output).sort(),
    relations: results.map((result) => ({
      path: result.output,
      input: result.primaryInput,
      dependencies: result.inputs.filter((input) => input !== result.primaryInput)
    })).sort((a, b) => a.path.localeCompare(b.path, 'en'))
  };
}
